from install_tests.install_test_env import Context, TestEnv

INDEX_TEXT = """[comment]: <> (This file is generated by mn-prompts. Do not edit directly.)

# Instructions

## The layers

Consult ./app_layer/index.md for app.

Consult ./local_env_layer/index.md for local_env.

Read the examples.
Consult ./python_lib_layer/index.md for python_lib.
"""

PYTHON_LIB_SNIPPET_TEXT = """---
requires: [app]
---


Read the examples.
Consult ./python_lib_layer/index.md for python_lib.


"""


def create_env(context: Context):
    return Env(context)


def test_generated_index(context: Context):
    # Create the test environment
    env = create_env(context)

    # We have an editable install of mn-prompts with the target python_lib,
    # which uses the layers local_env and python_lib (in that order). The
    # python_lib layer requires the app layer. Its snippet has blank lines
    # around the text.
    if env.step(
        env.install_editable(
            targets={"python_lib": ["python_lib", "local_env"]},
            layers={"app": [], "local_env": []},
        ),
        env.write_layer("python_lib", snippet_text=PYTHON_LIB_SNIPPET_TEXT),
        env.enter_project_dir(),
    ):
        pass

    # We install the python_lib target, and also ask for the python_lib layer.
    #
    # The layers should be ordered by name, and each layer should come after
    # the layers that it requires. The frontmatter and the blank lines around
    # the snippets should be stripped, and the python_lib layer should be
    # included once.
    if env.step(
        env.run_mn_prompts("install", "--target=python_lib", "--layer=python_lib"),
    ):
        assert env.exit_code == 0
        assert env.read_project_file("instructions/index.md") == INDEX_TEXT


class Env(TestEnv):
    pass
