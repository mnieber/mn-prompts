from install_tests.install_test_env import DJANGO_LAYERS, Context, TestEnv
from mn_prompts_test_env import AGENTS_FILE_TEXT

INDEX_TEXT = """[comment]: <> (This file is generated by mn-prompts. Do not edit directly.)

# Instructions

## The layers

Consult ./app_layer/index.md for app.

Consult ./python_lib_layer/index.md for python_lib.

Consult ./django_app_layer/index.md for django_app.
"""


def create_env(context: Context):
    return Env(context)


def test_a_user_installs_the_prompts_for_their_project(context: Context):
    # Create the test environment
    env = create_env(context)

    # We have an editable install of mn-prompts with the target django_app,
    # which uses the layers app and django_app. The django_app layer requires
    # the python_lib layer. We have an empty project dir.
    if env.step(
        env.install_editable(
            targets={"django_app": ["app", "django_app"]}, layers=DJANGO_LAYERS
        ),
        env.enter_project_dir(),
    ):
        pass

    # We install the prompts of the django_app target.
    #
    # It should create an instructions dir with an absolute symlink to each
    # layer of the target, and to the required python_lib layer, and a symlink
    # to the examples.
    if env.step(
        env.run_mn_prompts("install", "--target=django_app"),
    ):
        assert env.exit_code == 0
        assert not (env.project_dir / "instructions").is_symlink()
        assert env.instructions_entries() == [
            "app_layer",
            "django_app_layer",
            "examples",
            "index.md",
            "mn-prompts.yaml",
            "python_lib_layer",
        ]
        assert env.link("instructions/app_layer") == env.layer_dir("app")
        assert env.link("instructions/app_layer").is_absolute()
        assert env.link("instructions/python_lib_layer") == env.layer_dir("python_lib")
        assert env.link("instructions/django_app_layer") == env.layer_dir("django_app")
        assert env.link("instructions/examples") == env.prompts_dir / "examples"

    # We look at the generated files.
    #
    # The index should contain the snippets of the layers in the template, in
    # the order of their dependencies, and the manifest should record what we
    # asked for. The agents file should be copied to CLAUDE.md.
    if env.step():
        assert env.read_project_file("instructions/index.md") == INDEX_TEXT
        assert env.read_manifest() == {
            "target": "django_app",
            "layers": [],
            "agents_file": "CLAUDE.md",
        }
        assert env.read_project_file("CLAUDE.md") == AGENTS_FILE_TEXT


class Env(TestEnv):
    pass
